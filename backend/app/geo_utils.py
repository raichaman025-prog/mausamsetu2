"""
Lightweight geospatial helpers for the SQLite prototype.

In a PostGIS deployment, replace `haversine_km()` calls with a real
`ST_Distance` / `ST_DistanceSphere` query against `geom` columns — the
call sites (flood propagation endpoints) don't need to change shape.
"""
import math


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Great-circle distance between two lat/lon points, in kilometers."""
    R = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    d_phi = math.radians(lat2 - lat1)
    d_lambda = math.radians(lon2 - lon1)
    a = math.sin(d_phi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(d_lambda / 2) ** 2
    return R * 2 * math.atan2(math.sqrt(a), math.sqrt(1 - a))
